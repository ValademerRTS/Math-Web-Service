"""Модуль базовых арифметических операций."""


def add(a: float, b: float) -> float:
    """
    Возвращает сумму двух чисел.

    Параметры:
        a (float): Первое слагаемое.
        b (float): Второе слагаемое.

    Возвращаемое значение:
        float: Сумма чисел a и b.

    Пример вызова:
        >>> add(5, 3)
        8
    """
    return a + b


def subtract(a: float, b: float) -> float:
    """
    Возвращает разность двух чисел.

    Параметры:
        a (float): Уменьшаемое.
        b (float): Вычитаемое.

    Возвращаемое значение:
        float: Разность чисел a и b.

    Пример вызова:
        >>> subtract(10, 4)
        6
    """
    return a - b


def multiply(a: float, b: float) -> float:
    """
    Возвращает произведение двух чисел.

    Параметры:
        a (float): Первый множитель.
        b (float): Второй множитель.

    Возвращаемое значение:
        float: Произведение a и b.

    Пример вызова:
        >>> multiply(3, 7)
        21
    """
    return a * b


def divide(a: float, b: float):
    """
    Возвращает результат деления числа a на b.

    Параметры:
        a (float): Делимое.
        b (float): Делитель (не должен быть равен 0).

    Возвращаемое значение:
        float | str: Частное a и b, либо строка с ошибкой при делении на 0.

    Пример вызова:
        >>> divide(15, 3)
        5.0
        >>> divide(10, 0)
        'Ошибка: деление на ноль'
    """
    if b == 0:
        return "Ошибка: деление на ноль"
    return a / b


def power(a: float, b: float) -> float:
    """
    Возвращает результат возведения числа a в степень b.

    Параметры:
        a (float): Основание степени.
        b (float): Показатель степени.

    Возвращаемое значение:
        float: Число a, возведенное в степень b.

    Пример вызова:
        >>> power(2, 3)
        8
    """
    return a ** b